"""Streamlit churn demo with cached training on the public IBM sample data."""
from pathlib import Path
import sys
import joblib
import pandas as pd
import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))
from train import train

DATA_URL = "https://raw.githubusercontent.com/IBM/telco-customer-churn-on-icp4d/master/data/Telco-Customer-Churn.csv"
st.set_page_config(page_title="Telecom Churn Risk Explorer", page_icon="📊", layout="wide")
st.title("Telecom Customer Churn Risk Explorer")
st.markdown("Explore customer churn risk, compare validated machine-learning models, and discover predictive risk factors.")
st.caption("Educational machine-learning demo using the public IBM Telco Customer Churn sample.")

@st.cache_resource(show_spinner="Training and validating model on IBM telecom data (first launch)...")
def model_bundle():
    dataset = Path("data/telco_churn.csv")
    if not dataset.exists():
        dataset.parent.mkdir(parents=True, exist_ok=True)
        df = pd.read_csv(DATA_URL, dtype={"customerID": "string"})
        if len(df) != 7043 or "Churn" not in df:
            raise ValueError("Unexpected source dataset: please verify the IBM URL")
        df.to_csv(dataset, index=False)
    else:
        df = pd.read_csv(dataset)
    output = Path("artifacts")
    if not (output / "churn_model.joblib").exists():
        train(dataset, output)
    model = joblib.load(output / "churn_model.joblib")
    schema = joblib.load(output / "schema.joblib")
    import json
    metrics = json.loads((output / "metrics.json").read_text())
    return model, schema, metrics, df

try:
    model, schema, metrics, data = model_bundle()
except Exception as exc:
    st.error("Dataset or model initialization failed. Check the network connection and logs.")
    st.exception(exc)
    st.stop()

with st.sidebar:
    st.header("Model evaluation")
    st.write("Selected model:", metrics["selected_model"].replace("_", " ").title())
    test = metrics["held_out_test"][metrics["selected_model"]]
    st.metric("Held-out ROC-AUC", f'{test["roc_auc"]:.3f}')
    st.metric("Held-out accuracy", f'{test["accuracy"]:.1%}')
    st.metric("Held-out recall", f'{test["recall"]:.1%}')
    st.caption("Metrics are from a stratified 20% holdout. Model selection uses training-set CV.")

st.subheader("Try a customer profile")
defaults = data.copy()
if "TotalCharges" in defaults:
    defaults["TotalCharges"] = pd.to_numeric(defaults["TotalCharges"], errors="coerce")
values = {}
with st.form("prediction"):
    columns = st.columns(2)
    for i, name in enumerate(schema["features"]):
        with columns[i % 2]:
            if schema["types"][name] == "numeric":
                numbers = pd.to_numeric(defaults[name], errors="coerce")
                default = float(numbers.median()) if numbers.notna().any() else 0.0
                values[name] = st.number_input(name, value=default, step=1.0 if name in ("tenure", "SeniorCitizen") else 0.5)
            else:
                opts = schema["categories"][name]
                mode = defaults[name].mode(dropna=True)
                preferred = str(mode.iloc[0]) if not mode.empty else opts[0]
                values[name] = st.selectbox(name, opts, index=opts.index(preferred) if preferred in opts else 0)
    submitted = st.form_submit_button("Estimate churn probability", type="primary")

if submitted:
    probability = float(model.predict_proba(pd.DataFrame([values]))[0, 1])
    st.metric("Estimated churn probability", f"{probability:.1%}")
    st.progress(probability)
    st.caption("A prediction, not proof that a customer will leave. Do not use for consequential automated decisions.")

st.divider()
st.subheader("Model performance comparison")
report = Path("reports/model_evaluation.csv")
if report.exists():
    table = pd.read_csv(report)
    st.dataframe(table.rename(columns={
        "Model": "Model", "ROC_AUC": "ROC-AUC", "Average_Precision": "Average precision"
    }), hide_index=True, use_container_width=True)
    st.caption("These scores come from a fixed stratified 20% hold-out test set, not the customer entered above.")

st.subheader("What influences the model's predictions?")
shap_file = Path("reports/shap_importance.csv")
if shap_file.exists():
    impact = pd.read_csv(shap_file).head(10).copy()
    impact["feature"] = (impact["feature"]
        .str.replace("categorical__", "", regex=False)
        .str.replace("numeric__", "", regex=False)
        .str.replace("_", " ", regex=False))
    st.bar_chart(impact.set_index("feature")["mean_absolute_shap"], horizontal=True)
    st.caption("Mean absolute SHAP values from a held-out customer sample. Higher values mean larger model impact, not a causal effect or direction of churn risk.")

with st.expander("Model limitations and explanation"):
    st.write("This model captures historical associations, not causal drivers.")
    st.write("Global SHAP feature importance is generated by the separate src/explain.py workflow.")
    st.write("Explanations of individual predictions and calibrated decision thresholds require further validation.")
    st.write("For reproducibility, training and evaluation use random_state=42 and the same public source CSV.")
